/* =====================================================================
   Zenve BI — Lead Sources Subcategory
   Sidebar: Marketing > Lead Sources
   ===================================================================== */
(function () {
  'use strict';
  function launch() {
    if (window.ZenveMarketingDashboard && window.ZenveMarketingDashboard.open) {
      window.ZenveMarketingDashboard.open('lead-sources');
    }
  }

  if (window.location.hash === '#lead-sources') {
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', function () { setTimeout(launch, 250); });
    } else {
      setTimeout(launch, 250);
    }
  }
})();
